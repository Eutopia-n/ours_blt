"""Generate simulation wiring from the actual Sapphire wrapper port declarations."""
from pathlib import Path
import re
import struct
import zlib
import argparse

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--compact-asset',action='store_true',
                    help='Load one real sprite frame shared by 77 descriptors for load-focused simulation')
args=parser.parse_args()

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT/'vendor/soc/soc.v').read_text(encoding='utf-8')
header = source.split('module soc',1)[1].split(');',1)[0]
# Use the vendor's simulator-specific encrypted model, not the synthesis model.
# Preserve its contents; only the public wrapper's generated module name changes.
model = ROOT/'vendor/soc/EfxSapphireSoc_modelsim.v'
if not model.is_file():
    raise SystemExit(f'Missing vendor ModelSim model: {model}')
wrapper = source.split('endmodule',1)[0]+'endmodule\n'
wrapper = wrapper.replace('`IP_MODULE_NAME(EfxSapphireSoc)', 'EfxSapphireSoc ')
(ROOT/'sim/soc_modelsim.v').write_text(wrapper+model.read_text(encoding='utf-8'),encoding='utf-8')
ports = re.findall(r'\b(input|output)\s*(\[[^]]+\])?\s*(\w+)\s*[,\n]', header)
mapping = dict(io_systemClk='clk', io_memoryClk='clk', io_ddrMasters_0_clk='clk',
               io_asyncReset='reset', io_systemReset='soc_reset',
               io_ddrMasters_0_reset='master_reset', system_uart_0_io_rxd='uart_rx',
               system_uart_0_io_txd='uart_tx',
               system_gpio_0_io_read='key_state')
for field in ['PADDR','PENABLE','PRDATA','PREADY','PSEL','PSLVERROR','PWDATA','PWRITE']:
    mapping['io_apbSlave_0_'+field] = field.lower()
for channel in ['aw','w','b','ar','r']:
    for field in ['valid','ready']:
        mapping[f'io_ddrMasters_0_{channel}_{field}'] = channel+field
for channel, fields in [('aw',['addr','len']),('w',['data','strb','last']),
                        ('b',['resp']),('ar',['addr','len']),('r',['data','resp','last'])]:
    for field in fields:
        mapping[f'io_ddrMasters_0_{channel}_payload_{field}'] = channel+field
for channel in ['aw','ar']:
    mapping[f'io_ddrMasters_0_{channel}_payload_size'] = "3'd2"
    mapping[f'io_ddrMasters_0_{channel}_payload_burst'] = "2'b01"
decl=[]; inst=[]
for direction,width,name in ports:
    value=mapping.get(name)
    if name.startswith('io_ddrA_'):
        value='m_'+name[len('io_ddrA_'):].replace('_payload_','').replace('_','')
        kind='reg' if direction=='input' else 'wire'
        init=' = 0' if kind=='reg' else ''
        decl.append(f'{kind} {width} {value}{init};')
    if value is None:
        bits = int(width.strip('[]').split(':')[0])+1 if width else 1
        value='' if direction=='output' else f"{bits}'d0"
        if name.startswith('system_i2c'): value="1'b1" if direction=='input' else ''
    inst.append(f'    .{name}({value})')
text='// Generated by tools/prepare_soc_sim.py; do not edit.\n'
text+='\n'.join(decl)+'\nsoc cpu(\n'+',\n'.join(inst)+'\n);\n'
(ROOT/'sim/soc_wiring.vh').write_text(text)
app=(ROOT/'software/build/animation.bin')
asset=(ROOT/'assets/sprite77.raw')
if app.is_file() and asset.is_file():
    program=app.read_bytes()
    image=asset.read_bytes()
    suffix='_compact' if args.compact_asset else ''
    if args.compact_asset:
        offset,width,height,dx,dy=struct.unpack_from('<IBBbb',image,16)
        frame=image[offset:offset+width*height*2]
        table=struct.pack('<IBBbb',632,width,height,dx,dy)*77
        body=table+frame
        image=struct.pack('<IIII',0x37375341,1,16+len(body),zlib.crc32(body))+body
        print('Load-test asset:',len(image),'bytes; real first frame, 77 shared descriptors')
    app_header=struct.pack('<IIII',0x37505041,len(program),zlib.crc32(program),
                           struct.unpack_from('<I',image,12)[0])
    (ROOT/f'sim/app_image{suffix}.memh').write_text(''.join(f'{b:02x}\n' for b in app_header+program))
    (ROOT/f'sim/sprite77{suffix}.memh').write_text(''.join(f'{b:02x}\n' for b in image))
print('Generated real SoC simulation wiring:', len(ports), 'ports')
