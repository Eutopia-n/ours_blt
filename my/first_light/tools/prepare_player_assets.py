"""Convert the supplied 4x4 character sheet without changing its pixel artwork.

Requires Pillow only for regeneration; normal firmware builds use player_asset.h.
The firmware embeds one frame per direction. All 16 frames remain available for
the later game as an atlas and little-endian RGB565 data, with black as Color Key.
"""
from pathlib import Path
import hashlib
import json
import struct

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/player'
DIRECTIONS = ['down', 'left', 'right', 'up']
SIZE = 32


def character_box(cell):
    # Ignore detached marks in adjacent cells, keeping the largest opaque body.
    width, height = cell.size
    alpha = cell.getchannel('A')
    remaining = {y * width + x for y in range(height) for x in range(width)
                 if alpha.getpixel((x, y)) >= 128}
    largest = []
    while remaining:
        seed = remaining.pop()
        component = [seed]
        queue = [seed]
        while queue:
            pixel = queue.pop()
            x, y = pixel % width, pixel // width
            neighbours = []
            if x: neighbours.append(pixel - 1)
            if x + 1 < width: neighbours.append(pixel + 1)
            if y: neighbours.append(pixel - width)
            if y + 1 < height: neighbours.append(pixel + width)
            for neighbour in neighbours:
                if neighbour in remaining:
                    remaining.remove(neighbour)
                    component.append(neighbour)
                    queue.append(neighbour)
        if len(component) > len(largest): largest = component
    if not largest: raise ValueError('Empty character cell')
    return (min(p % width for p in largest), min(p // width for p in largest),
            max(p % width for p in largest) + 1, max(p // width for p in largest) + 1)


def rgb565(frame):
    pixels = []
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b, alpha = frame.getpixel((x, y))
            value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            # Opaque black must remain distinguishable from the transparent key.
            pixels.append(0 if alpha < 128 else value or 1)
    return pixels


def encode_rle(pixels, palette):
    encoded = []
    at = 0
    while at < len(pixels):
        count = 1
        while at + count < len(pixels) and count < 127 and pixels[at + count] == pixels[at]:
            count += 1
        encoded.append((count << 9) | palette.index(pixels[at]))
        at += count
    decoded = [palette[token & 511] for token in encoded for _ in range(token >> 9)]
    assert decoded == pixels and len(decoded) == SIZE * SIZE
    return encoded


def main():
    source = ASSETS / 'source.png'
    sheet = Image.open(source).convert('RGBA')
    atlas = Image.new('RGBA', (SIZE * 4, SIZE * 4))
    frames, boxes = [], []
    for row in range(4):
        for column in range(4):
            cell_box = (column * sheet.width // 4, row * sheet.height // 4,
                        (column + 1) * sheet.width // 4, (row + 1) * sheet.height // 4)
            cell = sheet.crop(cell_box)
            box = character_box(cell)
            body = cell.crop(box)
            scale = min(SIZE / body.width, SIZE / body.height)
            body = body.resize((max(1, round(body.width * scale)),
                                max(1, round(body.height * scale))), Image.Resampling.NEAREST)
            frame = Image.new('RGBA', (SIZE, SIZE))
            frame.paste(body, ((SIZE - body.width) // 2, SIZE - body.height))
            frames.append(rgb565(frame))
            boxes.append({'cell': list(cell_box), 'body': list(box)})
            atlas.paste(frame, (column * SIZE, row * SIZE))
    atlas.save(ASSETS / 'walk_32.png')
    (ASSETS / 'walk_32.rgb565').write_bytes(b''.join(struct.pack('<H', p) for f in frames for p in f))
    representative = [frames[row * 4] for row in range(4)]
    palette = sorted({p for frame in representative for p in frame})
    assert len(palette) <= 512, 'Firmware RLE tokens reserve 9 bits for the palette index'
    encoded, offsets = [], [0]
    for frame in representative:
        encoded.extend(encode_rle(frame, palette))
        offsets.append(len(encoded))
    compressed_bytes = 2 * (len(encoded) + len(palette))
    header = ['#ifndef PLAYER_ASSET_H', '#define PLAYER_ASSET_H',
              '/* Generated by tools/prepare_player_assets.py; directions: down, left, right, up. */',
              '#define PLAYER_FRAME_COUNT 4', f'#define PLAYER_RLE_BYTES {compressed_bytes}',
              f'static const unsigned short player_palette[{len(palette)}] = {{']
    header.extend('    ' + ', '.join(f'0x{p:04x}' for p in palette[at:at + 12]) + ','
                  for at in range(0, len(palette), 12))
    header.extend(['};', '/* Each token: 7-bit run length, 9-bit palette index. */',
                   f'static const unsigned short player_rle[{len(encoded)}] = {{'])
    header.extend('    ' + ', '.join(f'0x{p:04x}' for p in encoded[at:at + 12]) + ','
                  for at in range(0, len(encoded), 12))
    header.extend(['};', 'static const unsigned short player_rle_offsets[PLAYER_FRAME_COUNT + 1] = {' +
                   ', '.join(map(str, offsets)) + '};', '#endif', ''])
    (ROOT / 'software/player_asset.h').write_text('\n'.join(header), encoding='utf-8')
    # Independent uncompressed reference for testing the CPU upload/decoder.
    (ROOT / 'sim/player_expected.hex').write_text(
        ''.join(f'{p:04x}\n' for frame in representative for p in frame), encoding='ascii')
    metadata = {'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                'frame_width': SIZE, 'frame_height': SIZE, 'directions': DIRECTIONS,
                'frames_per_direction': 4, 'frame_index': 'direction * 4 + walk_frame',
                'pixel_format': 'RGB565 little-endian', 'color_key': 0,
                'bytes_per_frame': SIZE * SIZE * 2, 'row_stride': SIZE * 2,
                'firmware_frame_indices': [0, 4, 8, 12], 'firmware_rle_bytes': compressed_bytes,
                'crops': boxes}
    (ASSETS / 'walk_32.json').write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
    print(f'Prepared 16 frames ({len(frames) * SIZE * SIZE * 2} bytes); firmware RLE {compressed_bytes} bytes.')


if __name__ == '__main__': main()
